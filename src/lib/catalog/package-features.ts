export function parseFeaturesText(text: string | null | undefined): string[] {
  if (!text?.trim()) return [];
  let trimmed = text.trim();

  // Strip wrapping escaped quotes if double-encoded
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    try {
      const unquoted = JSON.parse(trimmed);
      if (typeof unquoted === "string") {
        trimmed = unquoted.trim();
      }
    } catch {
      trimmed = trimmed.slice(1, -1).trim();
    }
  }

  const cleanLine = (s: string) =>
    s
      .replace(/^(\s*[-•*]\s*|\s*\d+[.)]\s*|^\s*["'\[\]]+)+/, "")
      .replace(/["'\[\]]+$/, "")
      .replace(/\\"/g, '"')
      .trim();

  if (trimmed.startsWith("[") && trimmed.endsWith("]")) {
    try {
      const parsed = JSON.parse(trimmed);
      if (Array.isArray(parsed)) {
        return parsed
          .map((item) => cleanLine(String(item)))
          .filter((item) => item.length > 0);
      }
    } catch {
      // fallback to regex matching quoted strings inside bracket block
      const matches = trimmed.match(/"([^"\\]*(?:\\.[^"\\]*)*)"/g);
      if (matches && matches.length > 0) {
        return matches
          .map((m) => cleanLine(m))
          .filter((m) => m.length > 0);
      }
    }
  }
  return text
    .split(/\r?\n/)
    .map(cleanLine)
    .filter((l) => l.length > 0);
}

export function featuresForSlug(
  slug: string,
  longDescription?: string | null,
): string[] {
  const fromDb = parseFeaturesText(longDescription);
  if (fromDb.length) return fromDb;
  return PACKAGE_FEATURES[slug] ?? [...DEFAULT_FEATURES];
}

export function featuresTextFromList(features: string[]): string {
  return features.join("\n");
}

