/** Parse admin-entered features from longDescription (one bullet per line). */
export function parseFeaturesText(text: string | null | undefined): string[] {
  if (!text?.trim()) return [];
  return text
    .split(/\r?\n/)
    .map((l) => l.replace(/^[-•*\d.)\s]+/, "").trim())
    .filter((l) => l.length > 0);
}

export function featuresForSlug(
  slug: string,
  longDescription?: string | null,
): string[] {
  const fromDb = parseFeaturesText(longDescription);
  if (fromDb.length) return fromDb;
  return PACKAGE_FEATURES[slug] ?? [...DEFAULT_FEATURES];
}

export function featuresTextFromList(features: string[]): string {
  return features.join("\n");
}

