export function searchCuratedRepos(query: string): CuratedGithubRepo[] {
  const q = query.trim().toLowerCase();
  if (!q) return CURATED_GITHUB_REPOS;

  return CURATED_GITHUB_REPOS.filter(
    (repo) =>
      repo.name.toLowerCase().includes(q) ||
      repo.fullName.toLowerCase().includes(q) ||
      repo.description.toLowerCase().includes(q) ||
      repo.topics.some((t) => t.toLowerCase().includes(q)) ||
      repo.category.toLowerCase().includes(q) ||
      repo.language.toLowerCase().includes(q)
  );
}
